export function translate(lang: AdminLang, text: string, vars?: Record<string, string | number>): string {
  let out = lang === 'fr' ? (FR[text] ?? text) : text;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

